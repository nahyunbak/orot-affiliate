#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const config = require('./config');

console.log('🚀 Backend utils.ts 복사 스크립트 시작...');

// 경로 설정
const backendSrc = config.backend.src;
const mobileUtilsPath = path.join(__dirname, '../mobile/utils/backend');

// mobile/utils/backend 디렉토리 생성
function ensureDirectory(dirPath) {
  if (!fs.existsSync(dirPath)) {
    console.log('📁 디렉토리 생성:', dirPath);
    fs.mkdirSync(dirPath, { recursive: true });
  }
}

// backend/src/*/utils.ts 파일들 찾기
function findUtilsFiles() {
  console.log('🔍 Backend utils.ts 파일 검색 중...');

  const utilsFiles = [];
  const dirs = fs.readdirSync(backendSrc);

  for (const dir of dirs) {
    const dirPath = path.join(backendSrc, dir);
    const stat = fs.statSync(dirPath);

    if (stat.isDirectory()) {
      const utilsPath = path.join(dirPath, 'utils.ts');
      if (fs.existsSync(utilsPath)) {
        utilsFiles.push({
          sourcePath: utilsPath,
          moduleName: dir,
          targetFileName: `${dir}.ts`
        });
      }
    }
  }

  console.log(`✅ ${utilsFiles.length}개의 utils.ts 파일을 발견했습니다.`);
  return utilsFiles;
}

// DTO import 경로 변환
function transformImports(content, moduleName) {
  let transformed = content;

  // @/ 경로의 DTO import를 fetch/types로 변환
  // 예: import { MyPageResDto } from "@/user/dto/res.dto";
  // -> import { MyPageResDto } from "../../fetch/types";

  // 패턴 1: @/모듈/dto/파일 형태
  transformed = transformed.replace(
    /import\s+{([^}]+)}\s+from\s+['"]@\/[^'"]+\/dto\/[^'"]+['"]/g,
    'import {$1} from "../../fetch/types"'
  );

  // 패턴 2: ./dto/파일 형태 (상대 경로)
  transformed = transformed.replace(
    /import\s+{([^}]+)}\s+from\s+['"]\.\/dto\/[^'"]+['"]/g,
    'import {$1} from "../../fetch/types"'
  );

  // 패턴 3: ../다른모듈/dto/파일 형태
  transformed = transformed.replace(
    /import\s+{([^}]+)}\s+from\s+['"]\.\.\/[^'"]+\/dto\/[^'"]+['"]/g,
    'import {$1} from "../../fetch/types"'
  );

  // 중복 import 병합 (같은 from 경로를 가진 import들)
  const importMatches = transformed.match(/import\s+{([^}]+)}\s+from\s+["']\.\.\/\.\.\/fetch\/types["'];?/g);

  if (importMatches && importMatches.length > 1) {
    // 모든 import된 타입들을 수집
    const allTypes = new Set();
    for (const match of importMatches) {
      const typesMatch = match.match(/import\s+{([^}]+)}/);
      if (typesMatch) {
        const types = typesMatch[1].split(',').map(t => t.trim());
        types.forEach(t => allTypes.add(t));
      }
    }

    // 기존 import 문들 제거
    transformed = transformed.replace(/import\s+{[^}]+}\s+from\s+["']\.\.\/\.\.\/fetch\/types["'];?\n?/g, '');

    // 병합된 import 문 추가
    const mergedImport = `import { ${Array.from(allTypes).join(', ')} } from "../../fetch/types";\n`;
    transformed = mergedImport + transformed;
  }

  return transformed;
}

// 파일 복사 및 변환
function copyAndTransformFile(fileInfo) {
  const { sourcePath, moduleName, targetFileName } = fileInfo;
  const targetPath = path.join(mobileUtilsPath, targetFileName);

  console.log(`📄 복사 중: ${moduleName}/utils.ts -> ${targetFileName}`);

  // 원본 파일 읽기
  let content = fs.readFileSync(sourcePath, 'utf-8');

  // import 경로 변환
  content = transformImports(content, moduleName);

  // 파일 헤더 추가
  const header = `// This file is automatically generated from backend/${moduleName}/utils.ts
// DO NOT EDIT THIS FILE DIRECTLY - it will be overwritten
// To update this file, run: pnpm generate-api

`;

  content = header + content;

  // 파일 저장
  fs.writeFileSync(targetPath, content, 'utf-8');
  console.log(`✅ 저장 완료: ${targetPath}`);
}

// index.ts 파일 생성
function generateIndexFile(utilsFiles) {
  const indexPath = path.join(mobileUtilsPath, 'index.ts');

  let content = `// This file is automatically generated
// DO NOT EDIT THIS FILE DIRECTLY - it will be overwritten
// To update this file, run: pnpm generate-api

`;

  for (const fileInfo of utilsFiles) {
    const moduleName = fileInfo.moduleName;
    content += `export * from './${moduleName}';\n`;
  }

  if (utilsFiles.length === 0) content += 'export {};\n';
  fs.writeFileSync(indexPath, content, 'utf-8');
  console.log(`✅ index.ts 생성 완료: ${indexPath}`);
}

// 메인 실행 함수
function main() {
  console.log('📋 Backend utils 복사 작업을 시작합니다...\n');

  // 1. 대상 디렉토리 생성
  ensureDirectory(mobileUtilsPath);

  // 2. utils.ts 파일들 찾기
  const utilsFiles = findUtilsFiles();

  // 삭제된 원본의 생성물만 제거하고 사용자 정의 파일은 보존한다.
  const expected = new Set(utilsFiles.map((file) => file.targetFileName));
  for (const name of fs.readdirSync(mobileUtilsPath)) {
    const filePath = path.join(mobileUtilsPath, name);
    if (!expected.has(name) && fs.statSync(filePath).isFile() &&
        fs.readFileSync(filePath, 'utf8').startsWith('// This file is automatically generated from backend/')) {
      fs.unlinkSync(filePath);
    }
  }

  // 3. 각 파일 복사 및 변환
  for (const fileInfo of utilsFiles) {
    copyAndTransformFile(fileInfo);
  }

  // 4. index.ts 파일 생성
  generateIndexFile(utilsFiles);

  console.log('\n🎉 Backend utils 복사가 완료되었습니다!');
  console.log('💡 생성된 공통 유틸리티는 utils/backend에서 가져옵니다.');
}

// 스크립트 실행
if (require.main === module) {
  main();
}

module.exports = { main };
